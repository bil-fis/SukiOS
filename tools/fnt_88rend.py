# ---------------------------------------------------------------------------
# 渲染函数
# ---------------------------------------------------------------------------
def _glyph(code: int) -> list[int]:
    if code < 0x20 or code > 0x7E:
        code = ord('?')
    g = FONT8X8[code]
    assert g is not None          # 若还用 None 初始化
    return g


def render_char(ch, on='█', off=' '):
    """ch 可以是单个字符（'A'）或 ASCII 码（0x41 / 65）。"""
    code = ch if isinstance(ch, int) else ord(ch)
    glyph = _glyph(code)
    for row in range(8):
        bits = glyph[row]
        line = ''.join(on if (bits & (1 << col)) else off for col in range(8))
        print(line)


def render_string(s, on='█', off=' '):
    """把一行字符串按 8 行点阵渲染，字符之间留一列空隙。"""
    for row in range(8):
        parts = []
        for ch in s:
            bits = _glyph(ord(ch))[row]
            parts.append(''.join(on if (bits & (1 << col)) else off for col in range(8)))
        print(' '.join(parts))


def render_ascii_table(start=0x20, end=0x7E, per_line=8, on='█', off=' '):
    """把一段 ASCII 码表以每行 per_line 个字符的形式打印出来。"""
    codes = list(range(start, end + 1))
    for i in range(0, len(codes), per_line):
        chunk = codes[i:i + per_line]
        for row in range(8):
            parts = []
            for code in chunk:
                bits = _glyph(code)[row]
                parts.append(''.join(on if (bits & (1 << col)) else off for col in range(8)))
            print(' '.join(parts))
        print()  # 每个字符块之间空一行


