/* 帧缓冲像素写（xRGB32，内存 [B][G][R][X]） */
static void fb_put(uint32_t x, uint32_t y, uint32_t c)
{
    if (x >= g_width || y >= g_height) return;
    uint32_t off = y * (g_pitch / 4) + x;
    g_fb[off] = c;
}
/* 离屏层像素写 */
static void layer_put(uint32_t *layer, uint32_t x, uint32_t y, uint32_t c)
{
    if (x >= g_width || y >= g_height) return;
    layer[y * g_width + x] = c;
}

