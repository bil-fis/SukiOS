/* 按 codepoint 升序排列，供二分查找 */
static const struct {
    uint32_t cp;
    const uint8_t *data;
} g_cjk[] = {
    {0x4E16, cjk_shi},    /* 世 */
    {0x4E2D, cjk_zhong},  /* 中 */
    {0x4F5C, cjk_zuo},    /* 作 */
    {0x4F60, cjk_ni},     /* 你 */
    {0x5185, cjk_nei},    /* 内 */
    {0x529F, cjk_gong},   /* 功 */
    {0x52A8, cjk_dong},   /* 动 */
    {0x542F, cjk_qi},     /* 启 */
    {0x597D, cjk_hao},    /* 好 */
    {0x6210, cjk_cheng},  /* 成 */
    {0x6587, cjk_wen},    /* 文 */
    {0x6838, cjk_he},     /* 核 */
    {0x64CD, cjk_cao},    /* 操 */
    {0x7CFB, cjk_xi},     /* 系 */
    {0x7EDF, cjk_tong},   /* 统 */
    {0x754C, cjk_jie},    /* 界 */
};

bool font_cjk_get(uint32_t cp, const uint8_t **bits, int *w, int *h)
{
    int lo = 0, hi = (int)(sizeof(g_cjk) / sizeof(g_cjk[0])) - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        if (g_cjk[mid].cp == cp) {
            *bits = g_cjk[mid].data;
            *w = 16; *h = 16;
            return true;
        } else if (g_cjk[mid].cp < cp) {
            lo = mid + 1;
        } else {
            hi = mid - 1;
        }
    }
    return false;
}
