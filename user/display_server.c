/*
 * user/display_server.c
 * -----------------------------------------------------------------------------
 * SukiOS 显示服务（Ring3，进程 pid=6，由 kmain 经 task_create_user 内嵌拉起）。
 *
 * 职责（混合内核模型：显示合成是用户态服务，经 mach_msg 接收来自：
 *   - INPUT_SERVER  的文本/键盘事件（DISP_MSG_TEXT / DISP_MSG_KEY）
 *   - MOUSE_SERVER  的鼠标光标事件（MOUSE_MSG_MOVE/BUTTON/WHEEL）
 *   - 内核/其他服务 的调试文本（SYS_DEBUG_WRITE -> DISP_MSG_TEXT 转发）
 * 然后把合成结果写入内核映射给本进程的帧缓冲物理页（FB_USER_VA）。
 *
 * v1（旧架构缺陷）：单层直接写帧缓冲，光标用「像素快照法」直接改显存像素。
 *   这导致终端文本层与鼠标光标层在同一帧缓冲上互相覆盖 —— 模式问题：
 *     - 移动鼠标直接改显存像素；shell 输出字符重绘时把光标像素擦成字符，
 *       看起来就像「移动鼠标出现字符、满屏滚屏」。
 *     - 光标快照还会破坏底层桌面/文本像素，造成残影。
 *
 * v2（本版本，step48 修复）：【完整多层渲染，最后合并输出】
 *   ┌─────────────┐  ┌──────────────┐  ┌──────────────────┐
 *   │ 桌面层 L0   │  │ 终端文本层 L1 │  │ 鼠标光标 overlay │
 *   │(背景/边框)  │  │(字符网格光栅)│  │(实时透明叠加)   │
 *   └──────┬──────┘  └──────┬───────┘  └────────┬─────────┘
 *          └────────────────┴───────────────────┘
 *                         │ compose()
 *                         ▼
 *                  帧缓冲（物理显存 FB_USER_VA）
 *
 *   三层各自独立维护，互不破坏：
 *     L0 桌面层：静态（仅 draw_desktop 时重绘）。
 *     L1 文本层：完整字符网格 g_cells[ROWS][COLS]（含前景色），滚动移动文本，
 *               合成时整屏光栅化到文本层像素（背景透明，保留 L0）。
 *     L2 光标：仅存绝对坐标 + 可见性 + 按钮态，合成时按光标位图透明叠加。
 *   compose() 每帧：L0 -> 帧缓冲；叠加 L1（仅字形前景，背景透）；叠加 L2 光标。
 *
 * 红线：仅用合法 syscall 与 mach_msg，绝不 inb/outb（Ring3 无 IO 权限会 #GP）；
 *       用户指针由内核 copy_to_user 填，本进程不直解引用内核指针。
 * -----------------------------------------------------------------------------
 */
#include <stdint.h>
#include <stdbool.h>
#include <sukios/posix.h>
#include "lib/suki.h"

/* 端口与消息类型。
 * DISPLAY_PORT / MOUSE_PORT / INPUT_PORT / SHELL_PORT 等端口号取自 suki.h（统一权威定义），
 * 不再本地重定义，避免与 mouse_server / shell / input_server / 内核转发路径的端口号漂移。
 *
 * 关键：文本与鼠标事件都经 DISPLAY_PORT 投递，且历史代码中二者 msgh_id 都曾为 1，
 * 导致显示服务无法区分。本版本与 mouse_server 约定采用【msgh_id 分区】彻底消除歧义：
 *   - 文本：DISP_MSG_TEXT = 1（由内核 user_puts 转发、shell 经 sys_debug_write 输出）
 *   - 鼠标：MOUSE_MSG_MOVE = 101 / BUTTON = 102 / WHEEL = 103（mouse_server 专用 id 段）
 * 显示服务主循环按 msgh_id 直接区分，不再依赖 local_port/remote_port 判断。 */
#define DISP_MSG_TEXT  1   /* 文本块（含 '\n' 走换行；用于 shell 输出、内核转发） */
#define DISP_MSG_KEY   2   /* 键盘按键（保留，当前未用） */
#define DISP_MSG_CLEAR 3   /* 清屏 */

/* 鼠标事件 id 段（与 mouse_server.c 严格一致，必须 >=100 不与文本/FS 等冲突） */
#define MOUSE_MSG_MOVE   101
#define MOUSE_MSG_BUTTON 102
#define MOUSE_MSG_WHEEL  103

/* 字体与终端网格 */
#define CHAR_W 8
#define CHAR_H 16
#define ROWS 45
#define COLS 160

/* 颜色（xRGB32 内存布局 [B][G][R][X]，与 QEMU std VGA BGR 匹配） */
#define COL_BG       0x00101828u   /* 桌面深蓝 */
#define COL_TITLEBAR 0x00283050u
#define COL_WINBORDER 0x005a6a8a
#define COL_TEXT_FG  0x00e8e8e8u
#define COL_TEXT_DIM 0x0090a0b0u
#define COL_CURSOR_B 0x00000000u   /* 光标外框黑 */
#define COL_CURSOR_W 0x00ffffffu   /* 光标内白 */

/* 字符网格单元 */
typedef struct cell {
    uint8_t ch;
    uint32_t fg;
} cell_t;

/* 帧缓冲映射结果（SYS_FRAMEBUFFER_MAP copy_to_user 填充）。
 * 必须与内核 include/kernel/framebuffer.h 的 fb_map_result_t 逐字节布局一致：
 *   uint32_t enabled; uint64_t fb_user_va(对齐到 offset 8); uint64_t fb_phys;
 *   uint32_t pitch; uint32_t width; uint32_t height; uint32_t bpp;
 *   uint32_t cfg_width; uint32_t cfg_height;
 * 注意 enabled 为 uint32_t 后跟 uint64_t，编译器会在 offset 4..7 插入 4 字节填充，
 * 故 fb_user_va 实际位于 offset 8，与内核侧完全一致。 */
typedef struct fb_map_result {
    uint32_t enabled;
    uint32_t _pad0;
    uint64_t fb_user_va;
    uint64_t fb_phys;
    uint32_t pitch;
    uint32_t width;
    uint32_t height;
    uint32_t bpp;
    uint32_t cfg_width;
    uint32_t cfg_height;
} fb_map_result_t;

/* 显示文本消息（含内嵌文本，安全截断） */
typedef struct disp_text_msg {
    mach_msg_header_t h;
    char text[1024];
} disp_text_msg_t;

/* 鼠标事件消息（与 mouse_server 逐字节一致） */
typedef struct mouse_event_msg {
    mach_msg_header_t h;
    int32_t  x;
    int32_t  y;
    uint8_t  buttons;
    int8_t   wheel;
    uint8_t  _pad[3];
} mouse_event_msg_t;

