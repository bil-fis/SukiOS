/* ---------------------------------------------------------------------------
 * L0 桌面层：绘制背景 + 标题栏 + 窗口边框（静态，仅 draw_desktop 调用）
 * ------------------------------------------------------------------------- */
static void draw_desktop(void)
{
    if (!g_desktop_layer) return;
    for (uint32_t y = 0; y < g_height; y++) {
        uint32_t bg = COL_BG;
        if (y < 28) bg = COL_TITLEBAR;          /* 标题栏 */
        for (uint32_t x = 0; x < g_width; x++) {
            layer_put(g_desktop_layer, x, y, bg);
        }
    }
    /* 窗口边框（终端客户区外缘），留出标题栏 */
    uint32_t bx0 = 0, by0 = 28, bx1 = g_width - 1, by1 = g_height - 1;
    for (uint32_t x = bx0; x <= bx1; x++) {
        layer_put(g_desktop_layer, x, by0, COL_WINBORDER);
        layer_put(g_desktop_layer, x, by1, COL_WINBORDER);
    }
    for (uint32_t y = by0; y <= by1; y++) {
        layer_put(g_desktop_layer, bx0, y, COL_WINBORDER);
        layer_put(g_desktop_layer, bx1, y, COL_WINBORDER);
    }
}

/* ---------------------------------------------------------------------------
 * L1 终端文本层：把字符网格 g_cells 光栅化到 g_text_layer（背景透明=保留 L0）
 * ------------------------------------------------------------------------- */
static void draw_glyph(uint32_t *layer, uint32_t ox, uint32_t oy, uint8_t ch, uint32_t fg)
{
    if (ch < 32 || ch > 126) ch = 32;
    const uint8_t *g = g_font[ch - 32];
    for (int row = 0; row < 16; row++) {
        uint8_t bits = g[row];
        for (int col = 0; col < 8; col++) {
            if (bits & (0x80 >> col)) {
                layer_put(layer, ox + col, oy + row, fg);
            }
            /* 背景像素保持层缓冲原值（桌面层拷贝而来），实现透明叠加 */
        }
    }
}

static void rasterize_text_layer(void)
{
    if (!g_text_layer) return;
    /* 先用桌面层内容填充文本层（透明背景），再叠加字形 */
    u_memcpy(g_text_layer, g_desktop_layer, (size_t)g_width * g_height * sizeof(uint32_t));
    /* 终端客户区起点（标题栏下方 + 2px） */
    uint32_t oy0 = 28 + 2;
    for (int r = 0; r < ROWS; r++) {
        for (int c = 0; c < COLS; c++) {
            cell_t *cl = &g_cells[r][c];
            if (cl->ch == 0) continue;
            uint32_t px = (uint32_t)c * CHAR_W;
            uint32_t py = oy0 + (uint32_t)r * CHAR_H;
            if (px + CHAR_W > g_width) break;
            if (py + CHAR_H > g_height) return;
            draw_glyph(g_text_layer, px, py, cl->ch, cl->fg);
        }
    }
    g_text_dirty = 0;
}

/* ---------------------------------------------------------------------------
 * 终端文本网格操作（与帧缓冲解耦，滚动移动文本）
 * ------------------------------------------------------------------------- */
static void term_newline(void)
{
    g_term_col = 0;
    g_term_row++;
    if (g_term_row >= ROWS) {
        /* 上滚一行：移动文本而非清屏 */
        memmove(&g_cells[0][0], &g_cells[1][0], (size_t)(ROWS - 1) * COLS * sizeof(cell_t));
        u_memset(&g_cells[ROWS - 1][0], 0, COLS * sizeof(cell_t));
        g_term_row = ROWS - 1;
    }
    g_text_dirty = 1;
}

static void term_putc(char ch)
{
    if (ch == '\n') {
        term_newline();
        return;
    }
    if (ch == '\r') {
        g_term_col = 0;
        return;
    }
    if (ch == '\t') {
        for (int i = 0; i < 4; i++) {
            if (g_term_col >= COLS) { term_newline(); break; }
            g_cells[g_term_row][g_term_col].ch = ' ';
            g_cells[g_term_row][g_term_col].fg = COL_TEXT_FG;
            g_term_col++;
        }
        g_text_dirty = 1;
        return;
    }
    if (ch < 32) return;  /* 其它控制字符忽略 */
    if (g_term_col >= COLS) term_newline();
    g_cells[g_term_row][g_term_col].ch = (uint8_t)ch;
    g_cells[g_term_row][g_term_col].fg = COL_TEXT_FG;
    g_term_col++;
    g_text_dirty = 1;
}

static void term_write(const char *s, int n)
{
    for (int i = 0; i < n && s[i]; i++) {
        term_putc(s[i]);
    }
}

static void term_clear(void)
{
    u_memset(&g_cells[0][0], 0, ROWS * COLS * sizeof(cell_t));
    g_term_row = 0;
    g_term_col = 0;
    g_text_dirty = 1;
}

/* ---------------------------------------------------------------------------
 * L2 光标 overlay：合成时按当前位置叠加到帧缓冲（不落持久层）
 * ------------------------------------------------------------------------- */
static void draw_cursor_overlay(void)
{
    if (!g_cursor_visible) return;
    int32_t ox = g_cursor_x;
    int32_t oy = g_cursor_y;
    for (int r = 0; r < CUR_H; r++) {
        for (int c = 0; c < CUR_W; c++) {
            uint8_t m = g_cursor_mask[r][c];
            if (m == 0) continue;
            int32_t x = ox + c;
            int32_t y = oy + r;
            if (x < 0 || y < 0 || (uint32_t)x >= g_width || (uint32_t)y >= g_height) continue;
            fb_put((uint32_t)x, (uint32_t)y, m == 1 ? COL_CURSOR_B : COL_CURSOR_W);
        }
    }
}

/* ---------------------------------------------------------------------------
 * 合成：L0 -> 帧缓冲；叠加 L1（已含透明背景）；叠加 L2 光标
 * ------------------------------------------------------------------------- */
static void compose(void)
{
    if (!g_fb || !g_desktop_layer) return;
    if (g_text_dirty) {
        rasterize_text_layer();   /* 重光栅化 L1（基于桌面层背景透明叠加） */
    }
    /* L0+L1：直接整屏复制文本层结果到帧缓冲 */
    u_memcpy(g_fb, g_text_layer, (size_t)g_width * g_height * sizeof(uint32_t));
    /* L2：光标 overlay（带透明掩码，仅在掩码置位处改写像素） */
    draw_cursor_overlay();
    g_cursor_dirty = 0;
}

/* 把鼠标坐标（mouse_server 基于 1024x768 累计）按实际分辨率二次 clamp */
static int32_t clamp_x(int32_t x) { if (x < 0) return 0; if (x >= (int32_t)g_width)  return (int32_t)g_width - 1;  return x; }
static int32_t clamp_y(int32_t y) { if (y < 0) return 0; if (y >= (int32_t)g_height) return (int32_t)g_height - 1; return y; }

/* 调试输出辅助：u_print 仅接受单一字符串，故提供小工具把数字拼成串打印。 */
static void dbg_u32(const char *pre, uint32_t v, const char *suf)
{
    char tmp[32];
    uint32_t i = 0;
    /* 简单十进制转换 */
    char rev[12];
    uint32_t ri = 0, t = v;
    if (t == 0) { rev[ri++] = '0'; }
    while (t) { rev[ri++] = (char)('0' + (t % 10)); t /= 10; }
    while (ri) tmp[i++] = rev[--ri];
    if (pre) { uint32_t k = 0; while (pre[k]) tmp[i++] = pre[k++]; }
    if (suf) { uint32_t k = 0; while (suf[k]) tmp[i++] = suf[k++]; }
    tmp[i] = '\0';
    u_print(tmp);
}

/* ---------------------------------------------------------------------------
 * 入口
 * ------------------------------------------------------------------------- */
static void display_server_main(void)
{
    sys_port_claim(DISPLAY_PORT);

    fb_map_result_t fb;
    if (suki_syscall2(SYS_FRAMEBUFFER_MAP, (uint64_t)&fb, 0) != 0 || fb.enabled == 0) {
        u_print("[display] framebuffer unavailable; cannot start\n");
        sys_exit(1);
        return;
    }
    g_fb     = (uint32_t *)(uintptr_t)fb.fb_user_va;
    g_pitch  = (uint32_t)fb.pitch;
    g_width  = (uint32_t)fb.width;
    g_height = (uint32_t)fb.height;
    g_bpp    = (uint32_t)fb.bpp;

    /* 分配多层离屏缓冲（匿名映射，按需分页） */
    size_t fbsize = (size_t)g_width * g_height * sizeof(uint32_t);
    g_desktop_layer = (uint32_t *)sys_mmap(fbsize, SUKI_PROT_READ | SUKI_PROT_WRITE);
    g_text_layer    = (uint32_t *)sys_mmap(fbsize, SUKI_PROT_READ | SUKI_PROT_WRITE);
    if (!g_desktop_layer || !g_text_layer) {
        u_print("[display] layer alloc failed\n");
        sys_exit(1);
        return;
    }
    u_memset(g_desktop_layer, 0, fbsize);
    u_memset(g_text_layer, 0, fbsize);

    /* 初始光标位置：屏幕中心（基于实际分辨率） */
    g_cursor_x = (int32_t)(g_width / 2);
    g_cursor_y = (int32_t)(g_height / 2);

    draw_desktop();
    term_clear();
    term_write("SukiOS Display Server (multi-layer compose v2)\n", 45);

    /* 关键握手：声明显示服务就绪（置 g_display_active），内核引导线程据此
     * 屏障之后才挂载 mouse-server / shell。 */
    suki_syscall1(SYS_DISPLAY_READY, 0);

    /* 合成首帧并上屏 */
    compose();

    u_print("display: fb mapped at user va (");
    dbg_u32("", g_width, "x");
    dbg_u32("", g_height, "@");
    dbg_u32("", g_bpp, ")\n");
    u_print("[display] active: kernel console text now routed to display server\n");

    /* 消息循环 */
    uint8_t buf[1536];
    for (;;) {
        int n = mach_msg_recv(buf, sizeof(buf), DISPLAY_PORT);
        if (n <= 0) {
            sys_yield();
            continue;
        }
        mach_msg_header_t *h = (mach_msg_header_t *)buf;
        int dirty = 0;
        switch (h->msgh_id) {
            case DISP_MSG_TEXT: {
                disp_text_msg_t *m = (disp_text_msg_t *)buf;
                term_write(m->text, n - (int)sizeof(mach_msg_header_t));
                dirty = 1;
                break;
            }
            case DISP_MSG_KEY: {
                /* 键盘事件（保留位，当前未使用） */
                dirty = 0;
                break;
            }
            case DISP_MSG_CLEAR: {
                term_clear();
                dirty = 1;
                break;
            }
            case MOUSE_MSG_MOVE:
            case MOUSE_MSG_BUTTON:
            case MOUSE_MSG_WHEEL: {
                /* 鼠标事件（mouse_server 经 MOUSE_MSG_* id 段投递，与文本 id=1 不冲突） */
                mouse_event_msg_t *m = (mouse_event_msg_t *)buf;
                int32_t nx = clamp_x(m->x);
                int32_t ny = clamp_y(m->y);
                if (nx != g_cursor_x || ny != g_cursor_y) {
                    g_cursor_x = nx;
                    g_cursor_y = ny;
                    dirty = 1;
                }
                if (m->buttons != g_cursor_buttons) {
                    g_cursor_buttons = m->buttons;
                    g_cursor_visible = 1;
                    dirty = 1;
                }
                break;
            }
            default:
                break;
        }
        if (dirty) {
            compose();
        }
        sys_yield();
    }
}

int main(void)
{
    display_server_main();
    return 0;
}
